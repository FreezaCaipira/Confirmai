    public UiTextService(LanguagePreferenceService language)
    {
        _language = language;
    }

    public string this[string key] => Get(key);

    public string Get(string key)
    {
        if (TryGet(_language.SelectedLanguage, key, out var value))
        {
            return value;
        }

        if (TryGet(LanguagePreferenceService.DefaultLanguage, key, out value))
        {
            return value;
        }

        return key;
    }

    private static bool TryGet(string languageCode, string key, out string value)
    {
        value = string.Empty;

        if (!TextByLanguage.TryGetValue(languageCode, out var map))
        {
            return false;
        }

        if (!map.TryGetValue(key, out var resolved) || string.IsNullOrWhiteSpace(resolved))
        {
            return false;
        }

        value = resolved;
        return true;
    }
